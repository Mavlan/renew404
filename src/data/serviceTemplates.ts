export function templateServiceDefaults(item: ServiceTemplate) {
  return {
    name: localizedTemplateName(item.id, item.name),
    categoryId: item.categoryId,
    iconKey: item.iconKey,
    color: item.brandColor,
    websiteUrl: item.officialUrl === 'https://' ? undefined : item.officialUrl,
    intervalValue: item.defaultBillingCycle.value,
    intervalUnit: item.defaultBillingCycle.unit,
  }
}

export function searchServiceTemplates(query: string, categoryId?: string): ServiceTemplate[] {
  const needle = query.trim().toLocaleLowerCase()
  return SERVICE_TEMPLATES.filter((item) => {
    if (categoryId && item.categoryId !== categoryId) return false
    if (!needle) return true
    return [
      item.name,
      localizedTemplateName(item.id, item.name),
      t(`category.${item.categoryId}`),
      ...item.aliases,
    ].some((value) => value.toLocaleLowerCase().includes(needle))
  })
}
